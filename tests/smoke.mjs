import * as L from './lib.mjs';
await L.launch(); L.testDefaults(); L.makeForm('t-contact', 'contact'); L.clearMail();
const p = await L.site();
await p.goto(L.formUrl('t-contact'));
await L.fill(p, { f_name: 'Kokido', f_email: 'kokido@example.test', f_message: 'Ahoy', f_topic: 'A question' });
const r = await L.submit(p);
L.ok(r, 'sent: ' + p.url() + ' ' + (await L.text(p, 'body')).slice(0, 300));
console.log(JSON.stringify(L.latest('t-contact')));
console.log((await L.waitMail(1)).map((m) => m.to + ' | ' + m.subject));
await L.close(); L.finish();
